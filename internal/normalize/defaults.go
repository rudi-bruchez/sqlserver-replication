// Package normalize turns a desired configuration into the one it means:
// every omitted property filled with its measured default (plan 3, R1).
package normalize

import "strings"

// Context is what a default depends on (spec "Omitted properties"). An empty
// PubType, SyncMethod or ArticleKind of an entry matches any value.
type Context struct {
	Object      string // publication, article, push_subscription, pull_subscription (sp_addsubscription), subscriber_pull_subscription (sp_addpullsubscription), snapshot_agent, push_agent, shared_push_agent, pull_agent, log_reader_agent, distributor, distribution_db, distpublisher, profile
	PubType     string // transactional, snapshot, or "" for any
	SyncMethod  string // a decode name, or "" for any
	ArticleKind string // table, view_schema_only, proc_schema_only, func_schema_only, or ""
}

// Default is the value a creation procedure stores for an omitted
// parameter, as one measured row shows it.
type Default struct {
	Context Context
	// Path is the model path pattern relative to the object (objectBases):
	// retention_hours, destination.schema, commands.insert.
	Path string
	// Value is the model value, as the export writes it: "" is NULL, a list
	// is written [a, b] (formatList). A command is the string form
	// decode.ParseCommand reads (CALL [dbo].[x]), not the exported mode and
	// procedure structure. It may hold the templates
	// {source_schema}, {source_name}, {schema} and {table}, which Fill
	// replaces with the article's source schema and name.
	Value string
	// Row is "<results file> <row id>":
	// "11-defaults D.sp_addpublication.transactional.@retention".
	Row string
	// Stored is the result field of that row, verbatim.
	Stored string
}

// objectBases gives, for each Object, the model path pattern its entries'
// paths are relative to. Objects that share a base never fill each other's
// paths: Normalize looks a subscription's properties up in the push or the
// pull objects by the subscription's type, and a distributor property in
// the one object that owns it (normalize.go, distributorOwner).
var objectBases = map[string]string{
	"publication":                  "publications[*]",
	"article":                      "publications[*].articles[*]",
	"push_subscription":            "publications[*].subscriptions[*]",
	"snapshot_agent":               "publications[*].snapshot_agent",
	"push_agent":                   "publications[*].subscriptions[*].distribution_agent",
	"shared_push_agent":            "publisher.shared_distribution_agents[*].distribution_agent",
	"pull_subscription":            "publications[*].subscriptions[*]",
	"subscriber_pull_subscription": "publications[*].subscriptions[*]",
	"pull_agent":                   "publications[*].subscriptions[*].pull_agent",
	"log_reader_agent":             "publisher.log_reader_agent",
	"distributor":                  "distributor",
	"distribution_db":              "distributor",
	"distpublisher":                "distributor",
	"profile":                      "agent_profiles[*]",
}

// Lookup returns the default of path for ctx: among the entries of the
// object whose non-empty fields equal ctx's, the one with the most non-empty
// fields, so that an exact SyncMethod and ArticleKind beat "". Two entries
// equally specific give the same value (TestDefaultsDecodeStored); the
// first is returned.
func Lookup(ctx Context, path string) (Default, bool) { return lookup(Defaults, ctx, path) }

func lookup(table []Default, ctx Context, path string) (Default, bool) {
	best, score := -1, -1
	for i, d := range table {
		if d.Path != path || d.Context.Object != ctx.Object {
			continue
		}
		s, ok := 0, true
		for _, f := range [][2]string{
			{d.Context.PubType, ctx.PubType},
			{d.Context.SyncMethod, ctx.SyncMethod},
			{d.Context.ArticleKind, ctx.ArticleKind},
		} {
			switch f[0] {
			case "":
			case f[1]:
				s++
			default:
				ok = false
			}
		}
		if ok && s > score {
			best, score = i, s
		}
	}
	if best < 0 {
		return Default{}, false
	}
	return table[best], true
}

// Fill replaces the templates of a value with the article's source schema
// and name: {source_schema} and {schema} by schema, {source_name} and
// {table} by name. A generated command procedure is named after both,
// glued (sp_MSins_{schema}{table}), or, under concurrent_c, where the
// destination owner is NULL, after the table alone (sp_MSins_{table}).
//
// The command template is only right while the owner and the table name
// together are at most 109 characters (measured by the Task 5 review: from
// 110 the generated name is truncated to 120 characters ending with a
// 10-digit number, and a 60-character schema with a 110-character table
// drops the schema). Normalize therefore keeps a generated procedure nil
// (rule 6, compared on its mode only) and never relies on a filled name.
//
// {schema} and {table} only occur inside a bracketed procedure name, so a
// ']' in them is doubled, as the server does (measured: table
// dbo.[rv_t16 x]]y] stored CALL [dbo].[sp_MSins_dborv_t16 x]]y]); the
// {source_*} templates are plain values and are not.
func Fill(value, schema, name string) string {
	bracketed := func(s string) string { return strings.ReplaceAll(s, "]", "]]") }
	return strings.NewReplacer("{source_schema}", schema, "{source_name}", name,
		"{schema}", bracketed(schema), "{table}", bracketed(name)).Replace(value)
}

// formatList writes a list value: [a, b], [] for an empty one.
func formatList(xs []string) string { return "[" + strings.Join(xs, ", ") + "]" }

// ParseList reads a list value written by formatList; ok is false when v is
// not a list.
func ParseList(v string) (xs []string, ok bool) {
	inner, ok := strings.CutPrefix(v, "[")
	if !ok {
		return nil, false
	}
	if inner, ok = strings.CutSuffix(inner, "]"); !ok {
		return nil, false
	}
	xs = []string{}
	if inner == "" {
		return xs, true
	}
	return strings.Split(inner, ", "), true
}

// entry is one row of a measured context: the parameter, the path it fills,
// the model value and the row's result field.
type entry struct{ param, path, value, stored string }

func e(param, path, value, stored string) entry { return entry{param, path, value, stored} }

// measured builds the entries of one row context, "<file> D.<procedure>.<context>".
func measured(rowContext string, ctx Context, es ...entry) []Default {
	out := make([]Default, len(es))
	for i, x := range es {
		out[i] = Default{Context: ctx, Path: x.path, Value: x.value, Row: rowContext + "." + x.param, Stored: x.stored}
	}
	return out
}

func concat(groups ...[]Default) []Default {
	var out []Default
	for _, g := range groups {
		out = append(out, g...)
	}
	return out
}

